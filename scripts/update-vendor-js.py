#!/usr/bin/env python3
"""
Vendors the UI apps' third-party JavaScript into src/main/resources/app/vendor/.

The apps used to load Leaflet and the MCP Apps SDK from unpkg at render time. Anything
served from there runs with the app's full privileges - it can call server tools and post
into the conversation - so a compromised CDN or package release would own every app.
Vendoring removes the third-party script origin entirely: AppHtmlLoader inlines these
files at serve time, the same way it inlines the Entur stylesheets.

Each package comes from its npm registry tarball and is checked against the registry's
pinned sha512 integrity before anything is extracted, so an upgrade is a reviewed change
to the versions and hashes below.

The SDK ships only as an ES module, and an ES module cannot be inlined and then imported
by URL. Its bundle has a single trailing `export{...}` clause and no import.meta or
dynamic import, so it is rewrapped as a classic script that defines a global:

    var McpExtApps = (function () { "use strict"; <bundle>; return { App: ... }; })();

The function scope keeps the bundle's minified top-level names from colliding with the
apps' own.

Outputs:
    app/vendor/leaflet.js     Leaflet, unchanged
    app/vendor/leaflet.css    Leaflet styles, unchanged
    app/vendor/ext-apps.js    MCP Apps SDK, rewrapped as above

Usage:
    scripts/update-vendor-js.py
"""

import base64
import hashlib
import io
import os
import re
import sys
import tarfile
import urllib.request

VENDOR_DIR = os.path.normpath(
    os.path.join(os.path.dirname(os.path.abspath(__file__)), os.pardir,
                 "src", "main", "resources", "app", "vendor")
)

LEAFLET_VERSION = "1.9.4"
LEAFLET_INTEGRITY = "sha512-nxS1ynzJOmOlHp+iL3FyWqK89GtNL8U8rvlMOsQdTTssxZwCXh8N2NB3GDQOL+YR3XnWyZAxwQixURb+FA74PA=="

EXT_APPS_VERSION = "0.4.2"
EXT_APPS_INTEGRITY = "sha512-paPStFzWQ6opPMipgXohj+oUwLcHuwRENNlXAWRAAMQL78gJL7gpMhMg61LHyDBMGKACkPUrHUl7gIYBsZiouQ=="

# Inlined into a <script> or <style> element, these would end it early.
FORBIDDEN = ("</script", "</style", "<!--")


def fetch_package(name, version, integrity):
    """The package tarball, verified against its registry integrity."""
    short = name.rsplit("/", 1)[-1]
    url = f"https://registry.npmjs.org/{name}/-/{short}-{version}.tgz"
    with urllib.request.urlopen(url, timeout=60) as resp:
        data = resp.read()
    algo, expected = integrity.split("-", 1)
    actual = base64.b64encode(hashlib.new(algo, data).digest()).decode()
    if actual != expected:
        sys.exit(f"{name}@{version}: integrity mismatch\n  expected {expected}\n  got      {actual}")
    return tarfile.open(fileobj=io.BytesIO(data), mode="r:gz")


def read_member(tar, path):
    """One file from the tarball, read in memory - nothing is extracted to disk."""
    member = tar.getmember(f"package/{path}")
    return tar.extractfile(member).read().decode("utf-8")


def wrap_ext_apps(bundle):
    exports = re.findall(r"export\s*\{([^}]*)\}\s*;?\s*$", bundle)
    if len(exports) != 1:
        sys.exit("ext-apps: expected exactly one trailing export clause - bundle layout changed")
    if "import.meta" in bundle or re.search(r"\bimport\s*\(", bundle):
        sys.exit("ext-apps: bundle uses import.meta or dynamic import - cannot run as a classic script")
    if re.search(r"(^|[;}])\s*(export|import)\s", bundle[: bundle.rfind("export")]):
        sys.exit("ext-apps: found an import/export besides the trailing clause")

    local = None
    for binding in exports[0].split(","):
        parts = binding.split(" as ")
        if parts[-1].strip() == "App":
            local = parts[0].strip()
    if not local:
        sys.exit("ext-apps: no App export found")

    body = re.sub(r"export\s*\{[^}]*\}\s*;?\s*$", "", bundle)
    return (
        f"/* @modelcontextprotocol/ext-apps@{EXT_APPS_VERSION} - generated by "
        "scripts/update-vendor-js.py, do not edit */\n"
        'var McpExtApps = (function () {\n"use strict";\n'
        f"{body}\n"
        f"return {{ App: {local} }};\n"
        "})();\n"
    )


def write(name, content):
    for seq in FORBIDDEN:
        if seq in content.lower():
            sys.exit(f"{name}: contains {seq!r}, which would break out of the inlined element")
    path = os.path.join(VENDOR_DIR, name)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(content)
    print(f"wrote {os.path.relpath(path)} ({len(content):,} chars)")


def main():
    os.makedirs(VENDOR_DIR, exist_ok=True)

    leaflet = fetch_package("leaflet", LEAFLET_VERSION, LEAFLET_INTEGRITY)
    write("leaflet.js", read_member(leaflet, "dist/leaflet.js"))
    write("leaflet.css", read_member(leaflet, "dist/leaflet.css"))

    ext_apps = fetch_package("@modelcontextprotocol/ext-apps", EXT_APPS_VERSION, EXT_APPS_INTEGRITY)
    write("ext-apps.js", wrap_ext_apps(read_member(ext_apps, "dist/src/app-with-deps.js")))


if __name__ == "__main__":
    main()
